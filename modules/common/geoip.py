@dataclass
class _GeoRange:
    start: int
    end: int
    region: str


class GeoIP:
    """离线地区查询器：mmdb 优先，内置表兜底。"""

    def __init__(self, mmdb_path: str = DEFAULT_MMDB_PATH) -> None:
        self._reader: Optional[object] = None
        self._ranges: list[_GeoRange] = []
        self._loaded_from = "builtin"

        if os.path.isfile(mmdb_path):
            try:
                import maxminddb  # 延迟导入，仅在有 mmdb 文件时依赖

                self._reader = maxminddb.open_database(mmdb_path, maxminddb.MODE_MMAP_EXT)
                self._loaded_from = f"mmdb: {mmdb_path}"
            except Exception as e:  # 文件损坏/库缺失 → 降级内置表
                print(f"[sub-sift] 警告: mmdb 加载失败({e})，降级使用内置表")
                self._reader = None
                self._loaded_from = "builtin"

        if self._reader is None:
            for start, end, region in DEFAULT_GEOIP:
                try:
                    self._ranges.append(
                        _GeoRange(
                            int(ipaddress.ip_address(start)),
                            int(ipaddress.ip_address(end)),
                            region.upper(),
                        )
                    )
                except ValueError:
                    continue
            # 范围小（更具体）的段优先匹配，避免大段（如 CN 14.0.0.0/8）
            # 抢先命中其中的子段（如 HK 14.198.0.0/16）
            self._ranges.sort(key=lambda r: (r.end - r.start, r.start))

    def lookup(self, ip: str) -> str | None:
        """返回 IP 对应地区（大写 alpha-2），未命中返回 None。"""
        if self._reader is not None:
            try:
                rec = self._reader.get(ip)
            except Exception:
                return None
            if rec is None:
                return None
            iso = (rec.get("country") or {}).get("iso_code")
            return iso.upper() if isinstance(iso, str) and iso else None

        try:
            addr = int(ipaddress.ip_address(ip))
        except ValueError:
            return None
        for r in self._ranges:
            if r.start <= addr <= r.end:
                return r.region
        return None

    @property
    def source(self) -> str:
        return self._loaded_from
